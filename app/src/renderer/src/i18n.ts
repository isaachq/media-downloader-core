export const MESSAGES: Readonly<Record<Language, Readonly<Record<MessageKey, string>>>> = {
  en,
  es,
  pt,
  id,
  hi,
  vi,
  th,
  tr,
  ar,
  fr,
  de,
  ru,
  zh,
  it,
}

export type Translate = (key: MessageKey, params?: Readonly<Record<string, string | number>>) => string

export function translator(language: Language): Translate {
  const table = MESSAGES[language]
  return (key, params) => {
    const text = table[key]
    return params ? text.replace(/\{(\w+)\}/g, (match, name: string) => String(params[name] ?? match)) : text
  }
}

export const I18nContext = createContext<Translate>(translator('en'))
export const useT = (): Translate => useContext(I18nContext)
