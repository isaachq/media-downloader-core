type SiteMessages = Record<
  | 'sites.title'
  | 'sites.intro'
  | 'sites.col.site'
  | 'sites.col.what'
  | 'sites.col.signIn'
  | 'sites.col.phone'
  | 'sites.notNeeded'
  | 'sites.yes'
  | 'sites.desktopOnly'
  | 'sites.signInFor'
  | 'sites.inlineSignIn'
  | 'sites.ytDlp'
  | 'sites.name.web'
  | 'sites.name.file'
  | `sites.${SiteLabel}.what`
  | `sites.${SignInSite}.needs`,
  string
>

/** One language's words as the app's dictionary keys: O(sites), once per dictionary. */
export function siteMessages(language: Language): SiteMessages {
  const words = SITE_WORDS[language]
  const messages: Record<string, string> = {
    'sites.title': words.title,
    'sites.intro': words.intro,
    'sites.col.site': words.colSite,
    'sites.col.what': words.colWhat,
    'sites.col.signIn': words.colSignIn,
    'sites.col.phone': words.colPhone,
    'sites.notNeeded': words.notNeeded,
    'sites.yes': words.yes,
    'sites.desktopOnly': words.desktopOnly,
    'sites.signInFor': words.signInFor,
    'sites.inlineSignIn': words.inlineSignIn,
    'sites.ytDlp': words.ytDlp,
    'sites.name.web': words.nameWeb,
    'sites.name.file': words.nameFile,
  }
  for (const [site, text] of Object.entries(words.what)) messages[`sites.${site}.what`] = text
  for (const [site, text] of Object.entries(words.needs)) messages[`sites.${site}.needs`] = text
  return messages as SiteMessages
}
